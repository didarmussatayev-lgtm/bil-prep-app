const f2 = (v: number) => v.toFixed(2);
const uniq = (segs: Seg[]): Seg[] => {
  const m = new Map<string, Seg>();
  for (const [a, b, c, d] of segs) {
    const p = f2(a) + "," + f2(b), q = f2(c) + "," + f2(d);
    const k = p < q ? p + "|" + q : q + "|" + p;
    if (!m.has(k)) m.set(k, [a, b, c, d]);
  }
  return [...m.values()];
};
const lines = (segs: Seg[]): It[] => uniq(segs).map(([a, b, c, d]) => Ln(a, b, c, d));
/** Ряд фигур слева направо с номерами шагов под ними. */
const row = (b: Bld, ns: number[], opts: { gap?: number; scale?: number; labels?: string[]; dots?: boolean } = {}) => {
  const gap = opts.gap ?? 1.4;
  const H = Math.max(...ns.map(b.h));
  let x = 0;
  const items: It[] = [];
  ns.forEach((n, i) => {
    items.push(...b.draw(n, x, 0));
    items.push(Tx(x + b.w(n) / 2, H + 1, opts.labels ? opts.labels[i] : String(i + 1)));
    x += b.w(n) + gap;
  });
  return { kind: "scene" as const, width: x - gap, height: H + 1.4, items, scale: opts.scale ?? 20 };
};
