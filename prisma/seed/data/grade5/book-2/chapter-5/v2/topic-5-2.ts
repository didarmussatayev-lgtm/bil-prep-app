const R = (x: number, y: number, fill: number | null = 1, w = 1, h = 1): It => ({ t: "rect", x, y, w, h, fill });
const D = (cx: number, cy: number, fill: number | null = 1, r = 0.3): It => ({ t: "circle", cx, cy, r, fill });
const Ln = (x1: number, y1: number, x2: number, y2: number, color = 2): It => ({ t: "line", x1, y1, x2, y2, color });
const Tx = (x: number, y: number, s: string): It => ({ t: "text", x, y, s, anchor: "middle" });
