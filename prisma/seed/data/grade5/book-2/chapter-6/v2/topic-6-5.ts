const fig = (f: Figure) => ":::figure " + JSON.stringify(f);
const must = (cond: boolean, msg: string) => { if (!cond) throw new Error("6.5: " + msg); };

/** Вопрос «что напротив грани X»: пять вариантов — остальные грани, верный стоит на месте pos. */
function oppChoice(net: Net, target: string, pos: number) {
  const ans = opposite(net, target);
  const others = net.map((c) => c.l).filter((l) => l !== target && l !== ans);
  const p = place(ans, others, pos);
  return { options: p.options, correct: p.letter, ans };
}

/** Рисунок-выбор «какой куб получится»: один верный и четыре «зеркальные» ошибки (или наоборот). */
function viewsGallery(net: Net, triples: [string, string, string][], faceFill?: (l: string) => number | undefined) {
  const blocks = triples.map(([t, l, r]) =>
    cubeBlock({ l: t, f: faceFill?.(t) }, { l, f: faceFill?.(l) }, { l: r, f: faceFill?.(r) }));
  return gallery(blocks, triples.map((_, i) => String(i + 1)), 5, 22, 0.8);
}
function wrongViews(net: Net, t: [string, string, string]): [string, string, string][] {
  const [a, b, c] = t;
  const oa = opposite(net, a), ob = opposite(net, b), oc = opposite(net, c);
  const w: [string, string, string][] = [[a, c, b], [oa, b, c], [a, b, oc], [a, ob, c]];
  w.forEach((x) => must(!showsView(net, ...x), `неверный вариант оказался верным: ${x}`));
  return w;
}
function correctViewTask(net: Net, t: [string, string, string], pos: number) {
  must(showsView(net, ...t), "верный вид не верен");
  const w = wrongViews(net, t);
  const p = place(t, w, pos);
  return { figs: viewsGallery(net, p.options), correct: p.letter, num: pos + 1 };
}
/** «Какой НЕ соответствует»: четыре верных вида из разных вершин и один неверный. */
function oddViewTask(net: Net, goodIdx: number[], bad: [string, string, string], pos: number) {
  const all = allViews(net);
  const good = goodIdx.map((i) => all[i]);
  must(!showsView(net, ...bad), "«лишний» вид оказался верным");
  const p = place(bad, good, pos);
  return { figs: viewsGallery(net, p.options), correct: p.letter, num: pos + 1 };
}

/** Набор рисунков развёртки без подписей (для вопросов «какая из фигур — развёртка»). */
function netsGallery(nets: Net[]) {
  const blocks = nets.map((n) => netBlock(n, { hide: true }));
  return gallery(blocks, nets.map((_, i) => String(i + 1)), 3, 17, 1);
}
function netPick(valid: string[][], invalid: string[][], wantValid: boolean, pos: number) {
  // wantValid: один верный среди неверных; иначе — один неверный среди верных
  const V = valid.map((r) => parseNet(r)), I = invalid.map((r) => parseNet(r));
  V.forEach((n, i) => must(isCubeNet(n), `развёртка ${i} должна быть верной`));
  I.forEach((n, i) => must(!isCubeNet(n), `фигура ${i} не должна быть развёрткой`));
  const p = wantValid ? place(V[0], I, pos) : place(I[0], V, pos);
  return { fig: netsGallery(p.options), correct: p.letter };
}

