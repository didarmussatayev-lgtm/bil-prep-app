const NUM5 = ["1", "2", "3", "4", "5"];
function oppTask(n: string, rows: string[], target: string, pos: number, q: string, why: string): SeedTask {
  const net = parseNet(rows);
  const c = oppChoice(net, target, pos);
  return { n, q, figure: netFigure(net), choice: { options: c.options, correct: c.correct as "A" }, solution: `${why} Ответ: ${c.ans}.` };
}
function viewTask(n: string, rows: string[], t: [string, string, string], pos: number, why: string): SeedTask {
  const net = parseNet(rows);
  const r = correctViewTask(net, t, pos);
  return {
    n, q: "Развёртку сложили в куб (надписи снаружи). Какой из кубиков 1–5 мог получиться?",
    figure: [netFigure(net), r.figs], choice: { options: NUM5, correct: r.correct as "A" },
    solution: `${why} Верный — кубик ${r.num}. На остальных кубиках буквы идут в другом порядке или рядом оказались буквы противоположных граней.`,
  };
}
function oddTask(n: string, rows: string[], good: number[], badFrom: number, badVariant: number, pos: number): SeedTask {
  const net = parseNet(rows);
  const all = allViews(net);
  const bad = wrongViews(net, all[badFrom])[badVariant];
  const r = oddViewTask(net, good, bad, pos);
  return {
    n, q: "Развёртку сложили в куб (надписи снаружи). Какой из кубиков 1–5 НЕ мог получиться из этой развёртки?",
    figure: [netFigure(net), r.figs], choice: { options: NUM5, correct: r.correct as "A" },
    solution: `Четыре кубика показывают три грани, которые действительно сходятся в одной вершине в правильном порядке. На кубике ${r.num} порядок граней зеркальный (или рядом стоят противоположные грани), такой куб из развёртки не получить.`,
  };
}

