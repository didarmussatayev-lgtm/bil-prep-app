/** Выбор номера стороны: верный ответ и четыре других номера из 1..14 на позиции pos. */
function sidePick(n: Net, id: number, pos: number) {
  const ans = gl(n, id);
  const pool: number[] = [];
  for (let k = 1; k <= 14; k++) if (k !== id && k !== ans) pool.push(k);
  // детерминированно берём «правдоподобные» — соседей по номеру и симметричные
  const near = [ans - 1, ans + 1, id + 1, id - 1, ans + 2, ans - 2].filter((k) => pool.includes(k));
  const wrong = [...new Set([...near, ...pool])].slice(0, 4);
  const p = place(ans, wrong, pos);
  return { ans, options: p.options.map(String), correct: p.letter };
}

