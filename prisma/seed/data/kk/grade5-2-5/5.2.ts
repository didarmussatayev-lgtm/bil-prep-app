// ---- рисунки: построители фигурных последовательностей (scene) ----
type It = Record<string, unknown>;
type Seg = [number, number, number, number];
type Bld = { draw: (n: number, ox: number, oy: number) => It[]; w: (n: number) => number; h: (n: number) => number };
const fig = (f: object) => ":::figure " + JSON.stringify(f);
const R = (x: number, y: number, fill: number | null = 1, w = 1, h = 1): It => ({ t: "rect", x, y, w, h, fill });
const D = (cx: number, cy: number, fill: number | null = 1, r = 0.3): It => ({ t: "circle", cx, cy, r, fill });
const Ln = (x1: number, y1: number, x2: number, y2: number, color = 2): It => ({ t: "line", x1, y1, x2, y2, color });
const Tx = (x: number, y: number, s: string): It => ({ t: "text", x, y, s, anchor: "middle" });
const Po = (pts: [number, number][], fill: number | null = 1): It => ({ t: "poly", pts, fill });
const f2 = (v: number) => v.toFixed(2);
const uniq = (segs: Seg[]): Seg[] => {
  const m = new Map<string, Seg>();
  for (const [a, b, c, d] of segs) {
    const p = f2(a) + "," + f2(b), q = f2(c) + "," + f2(d);
    const k = p < q ? p + "|" + q : q + "|" + p;
    if (!m.has(k)) m.set(k, [a, b, c, d]);
  }
  return [...m.values()];
};
const lines = (segs: Seg[]): It[] => uniq(segs).map(([a, b, c, d]) => Ln(a, b, c, d));
/** Ряд фигур слева направо с номерами шагов под ними. */
const row = (b: Bld, ns: number[], opts: { gap?: number; scale?: number; labels?: string[]; dots?: boolean } = {}) => {
  const gap = opts.gap ?? 1.4;
  const H = Math.max(...ns.map(b.h));
  let x = 0;
  const items: It[] = [];
  ns.forEach((n, i) => {
    items.push(...b.draw(n, x, 0));
    items.push(Tx(x + b.w(n) / 2, H + 1, opts.labels ? opts.labels[i] : String(i + 1)));
    x += b.w(n) + gap;
  });
  return { kind: "scene" as const, width: x - gap, height: H + 1.4, items, scale: opts.scale ?? 20 };
};
// треугольники из палочек (змейка), сторона 2
const TH = 1.7;
const triSegs = (n: number, ox: number, oy: number): Seg[] => {
  const s: Seg[] = [];
  for (let i = 0; i < n; i++) {
    const x0 = ox + i;
    const p: [number, number][] = i % 2 === 0 ? [[x0, oy + TH], [x0 + 2, oy + TH], [x0 + 1, oy]] : [[x0, oy], [x0 + 2, oy], [x0 + 1, oy + TH]];
    s.push([...p[0], ...p[1]], [...p[1], ...p[2]], [...p[2], ...p[0]]);
  }
  return s;
};
const tri: Bld = { draw: (n, ox, oy) => lines(triSegs(n, ox, oy)), w: (n) => n + 1, h: () => TH };
const triDots: Bld = {
  draw: (n, ox, oy) => {
    const pts = new Map<string, [number, number]>();
    for (const [a, b, c, d] of triSegs(n, ox, oy)) { pts.set(f2(a) + f2(b), [a, b]); pts.set(f2(c) + f2(d), [c, d]); }
    return [...lines(triSegs(n, ox, oy)), ...[...pts.values()].map(([x, y]) => D(x, y, 1, 0.16))];
  },
  w: (n) => n + 1, h: () => TH,
};
// ряд квадратов из палочек, сторона 1,4
const SQ = 1.4;
const sqSegs = (n: number, ox: number, oy: number): Seg[] => {
  const s: Seg[] = [];
  for (let i = 0; i < n; i++) {
    const x0 = ox + i * SQ;
    s.push([x0, oy, x0 + SQ, oy], [x0, oy + SQ, x0 + SQ, oy + SQ], [x0, oy, x0, oy + SQ], [x0 + SQ, oy, x0 + SQ, oy + SQ]);
  }
  return s;
};
const sqm: Bld = { draw: (n, ox, oy) => lines(sqSegs(n, ox, oy)), w: (n) => n * SQ, h: () => SQ };
const sqDots: Bld = {
  draw: (n, ox, oy) => {
    const d: It[] = [];
    for (let i = 0; i <= n; i++) d.push(D(ox + i * SQ, oy, 1, 0.16), D(ox + i * SQ, oy + SQ, 1, 0.16));
    return [...lines(sqSegs(n, ox, oy)), ...d];
  },
  w: (n) => n * SQ, h: () => SQ,
};
// цепочка шестиугольников из палочек
const HS = 0.9, HW = Math.sqrt(3) * HS;
const hexSegs = (n: number, ox: number, oy: number): Seg[] => {
  const s: Seg[] = [];
  for (let i = 0; i < n; i++) {
    const cx = ox + HW / 2 + i * HW, cy = oy + HS;
    const v = Array.from({ length: 6 }, (_, k) => [cx + HS * Math.cos(((30 + 60 * k) * Math.PI) / 180), cy + HS * Math.sin(((30 + 60 * k) * Math.PI) / 180)] as [number, number]);
    for (let k = 0; k < 6; k++) s.push([...v[k], ...v[(k + 1) % 6]]);
  }
  return s;
};
const hexm: Bld = { draw: (n, ox, oy) => lines(hexSegs(n, ox, oy)), w: (n) => n * HW, h: () => 2 * HS };
// угол из кружков (2n−1)
const ell: Bld = {
  draw: (n, ox, oy) => {
    const d: It[] = [];
    for (let i = 0; i < n; i++) d.push(D(ox + i + 0.5, oy + n - 0.5, 2));
    for (let j = 0; j < n - 1; j++) d.push(D(ox + 0.5, oy + j + 0.5, 2));
    return d;
  },
  w: (n) => n, h: (n) => n,
};
// кружки «тройки с краями» (3n+2)
const clus: Bld = {
  draw: (n, ox, oy) => {
    const d: It[] = [D(ox + 0.5, oy + 1.5, 4), D(ox + n + 1.5, oy + 1.5, 4)];
    for (let g = 1; g <= n; g++) for (let j = 0; j < 3; j++) d.push(D(ox + g + 0.5, oy + j + 0.5, 4));
    return d;
  },
  w: (n) => n + 2, h: () => 3,
};
// игральные кости с пятью точками (5n)
const dice: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [];
    for (let k = 0; k < n; k++) {
      const x = ox + k * 2.7;
      it.push(R(x, oy, null, 2.4, 2.4), D(x + 0.6, oy + 0.6, 1, 0.2), D(x + 1.8, oy + 0.6, 1, 0.2), D(x + 0.6, oy + 1.8, 1, 0.2), D(x + 1.8, oy + 1.8, 1, 0.2), D(x + 1.2, oy + 1.2, 1, 0.2));
    }
    return it;
  },
  w: (n) => n * 2.7 - 0.3, h: () => 2.4,
};
// пирамида из треугольников (n рядов, n² малых треугольников)
const PA = 1.2, PH = 1.04;
const pyr: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [];
    for (let r = 0; r < n; r++) {
      const x0 = ox + ((n - 1 - r) * PA) / 2, y = oy + r * PH;
      for (let j = 0; j <= r; j++) it.push(Po([[x0 + j * PA, y + PH], [x0 + (j + 1) * PA, y + PH], [x0 + j * PA + PA / 2, y]], 0));
      for (let j = 0; j < r; j++) it.push(Po([[x0 + j * PA + PA / 2, y], [x0 + j * PA + PA * 1.5, y], [x0 + (j + 1) * PA, y + PH]], 1));
    }
    return it;
  },
  w: (n) => n * PA, h: (n) => n * PH,
};
// рамка из квадратов (сторона n+1, 4n плиток)
const frame: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [], s = n + 1;
    for (let r = 0; r < s; r++) for (let c = 0; c < s; c++) if (r === 0 || c === 0 || r === s - 1 || c === s - 1) it.push(R(ox + c, oy + r, 3));
    return it;
  },
  w: (n) => n + 1, h: (n) => n + 1,
};
// лесенка: ряд r содержит r плиток (1+2+…+n)
const stairs: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [];
    for (let r = 0; r < n; r++) for (let c = 0; c <= r; c++) it.push(R(ox + c, oy + r, r % 2 === 0 ? 0 : 3));
    return it;
  },
  w: (n) => n, h: (n) => n,
};
// квадраты n×n, новый слой другим цветом
const lsq: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [];
    for (let r = 0; r < n; r++) for (let c = 0; c < n; c++) it.push(R(ox + c, oy + r, Math.max(r, c) === n - 1 ? 4 : 1));
    return it;
  },
  w: (n) => n, h: (n) => n,
};
// «П»: перекладина n+2 и две ножки по 3 плитки
const pi: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [];
    for (let c = 0; c < n + 2; c++) it.push(R(ox + c, oy, 5));
    for (let r = 1; r <= 3; r++) it.push(R(ox, oy + r, 5), R(ox + n + 1, oy + r, 5));
    return it;
  },
  w: (n) => n + 2, h: () => 4,
};
// крест из квадратов: длина луча n−1 (4n−3 плиток)
const plus: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [], m = n - 1;
    for (let k = -m; k <= m; k++) { it.push(R(ox + m + k, oy + m, 2)); if (k !== 0) it.push(R(ox + m, oy + m + k, 2)); }
    return it;
  },
  w: (n) => 2 * n - 1, h: (n) => 2 * n - 1,
};
// решётка из точек 3 × (n+1), соединённых отрезками
const dgrid: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [];
    for (let r = 0; r < 3; r++) it.push(Ln(ox, oy + r, ox + n, oy + r));
    for (let c = 0; c <= n; c++) it.push(Ln(ox + c, oy, ox + c, oy + 2));
    for (let r = 0; r < 3; r++) for (let c = 0; c <= n; c++) it.push(D(ox + c, oy + r, 1, 0.14));
    return it;
  },
  w: (n) => n, h: () => 2,
};
// ромб из точек: ряды 1,3,…,2n−1,…,3,1 (2n²−2n+1 точек)
const diamond: Bld = {
  draw: (n, ox, oy) => {
    const it: It[] = [], W = 2 * n - 1;
    for (let r = 0; r < 2 * n - 1; r++) {
      const cnt = 2 * (r < n ? r : 2 * n - 2 - r) + 1;
      for (let k = 0; k < cnt; k++) it.push(D(ox + (W - cnt) / 2 + k + 0.5, oy + r * 0.8 + 0.4, 5, 0.22));
    }
    return it;
  },
  w: (n) => 2 * n - 1, h: (n) => (2 * n - 1) * 0.8,
};
// ряды кружков: в k-м ряду 2k штук
const rowsEven = (k: number): Bld => ({
  draw: (_n, ox, oy) => {
    const it: It[] = [];
    for (let r = 1; r <= k; r++) for (let c = 0; c < 2 * r; c++) it.push(D(ox + c + 0.5, oy + r - 0.5, 3, 0.3));
    return it;
  },
  w: () => 2 * k, h: () => k,
});
// бусины: цвета 0 жёлтый, 1 голубой, 2 розовый, 3 зелёный
const beads = (cols: number[], scale = 20) => ({
  kind: "scene" as const, width: cols.length * 1.15 - 0.15, height: 1, scale,
  items: cols.map((c, i) => D(i * 1.15 + 0.5, 0.5, c, 0.5)),
});
// стенка 3 в ширину: в n-м шаге высота 7−n (3·(7−n) плиток)
const wall: Bld = {
  draw: (n, ox, oy) => {
    const h = 7 - n, it: It[] = [];
    for (let r = 0; r < h; r++) for (let c = 0; c < 3; c++) it.push(R(ox + c, oy + 6 - h + r, 3));
    return it;
  },
  w: () => 3, h: () => 6,
};

