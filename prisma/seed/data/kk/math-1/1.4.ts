/** Модель көбейту: қызылмен алғашқы `red` жол, көкпен алғашқы `blue` баған, күлгінмен — олардың ортақ бөлігі. */
const model = (rows: number, cols: number, red: number, blue: number, scale = 40): Figure => {
  const items: Record<string, unknown>[] = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const isRed = r < red;
      const isBlue = c < blue;
      const fill = isRed && isBlue ? "#A78BFA" : isRed ? "#FCA5A5" : isBlue ? "#93C5FD" : null;
      items.push({ t: "rect", x: c, y: r, w: 1, h: 1, fill });
    }
  }
  return { kind: "scene", width: cols, height: rows, items, scale };
};

